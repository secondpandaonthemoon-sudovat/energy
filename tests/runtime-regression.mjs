import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { siteConfig } from '../js/data/siteConfig.js';
import { loadRuntimeContent, runtimeContent, getHomeSections, getMenu, hasHomePage, hasMenu, resolveCmsHref, runCmsLink } from '../js/runtimeContent.js';
const state = JSON.parse(await readFile(new URL('../data/initial_state.json', import.meta.url)));
const metas = new Map();
globalThis.location = {search:''};
globalThis.document = {documentElement:{style:{setProperty(){}},dataset:{}}, title:'', head:{querySelector:()=>null,appendChild(el){metas.set(el.name,el)}}, createElement:()=>({setAttribute(){}}),getElementById:()=>null};
globalThis.fetch = async () => ({ok:true,json:async()=>state});
state.pages[0].sections.forEach(s=>s.enabled=false);
state.menus[0].items.forEach(s=>s.enabled=false);
state.entities.products[0].sortOrder=999;
state.entities.products[1].sortOrder=-1;
state.settings.site_config.__proto__ = undefined;
await loadRuntimeContent();
