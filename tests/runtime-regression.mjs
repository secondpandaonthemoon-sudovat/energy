assert.deepEqual(getHomeSections(),[],'all disabled sections remain hidden');
assert.equal(hasMenu('header'),true);
assert.deepEqual(getMenu('header'),[],'all disabled menu items remain hidden');
assert.equal(siteConfig.products[0].id,state.entities.products[1].id,'CMS entity sort order takes effect');
