assert.equal(resolveCmsHref({type:'page',target:'/products'}),'/products');
assert.equal(resolveCmsHref({type:'external',target:'https://example.com'}),'https://example.com');
assert.equal(resolveCmsHref({type:'external',target:'javascript:alert(1)'}),'#');
let dispatched;
globalThis.CustomEvent=class { constructor(type,options){this.type=type;this.detail=options.detail;} };
globalThis.window={dispatchEvent(event){dispatched=event;}};
runCmsLink({type:'product',target:'selected-product'});
